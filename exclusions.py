def is_excluded_sender(email):
    if email in EXCLUDED_SENDERS:
        return True
    local = re.sub(r"[._-]", "", email.split("@")[0])
    # Prefix only: a substring check would hit names like "forwardmarchindtech".
    return local.startswith("dmarc") or any(k in local for k in AUTOMATED_LOCAL_PART_KEYWORDS)
